"""
Page Title Elements

This file contains XPath locators for the page title elements.
"""

class PageTitleElements:
    """
    Class containing XPath locators for page title elements.
    """
    
    # Main content container
    div_main_content = "//div[@class='main-content']"
    
    # Content container
    div_content = "//div[@class='content']"
    
    # Page title
    div_page_title = "//div[@class='page-title']"
    span_text = "//div[@class='page-title']/span[@class='text']" 